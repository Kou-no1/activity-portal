import fs from 'node:fs';
const read = name => JSON.parse(fs.readFileSync(new URL(name, import.meta.url), 'utf8'));
const legacy = read('legacy-activities.json');
const metadata = read('legacy-meta.json');
const support = read('support-content.json');
const activities = [...legacy.map(item => {
  const {override = {}, ...meta} = metadata[item.id] || {};
  return {...item, ...override, ...meta};
}), ...support];
const issues = [
  {id:'listen', label:'話を聞けない', description:'ざわざわして、話を始められない', emoji:'👂'},
  {id:'switch', label:'切り替えが遅い', description:'休み時間や活動のあとが落ち着かない', emoji:'🌿'},
  {id:'routine', label:'朝・給食・帰りの会', description:'生活の場面をスムーズに進めたい', emoji:'☀️'},
  {id:'conflict', label:'言い争い・悪口', description:'気持ちの伝え方や関わり方を育てたい', emoji:'💬'},
  {id:'cooperate', label:'協力してほしい', description:'安心して一緒に取り組める学級に', emoji:'🤝'}
];
const stages = [
  {id:'now', label:'今、その場で整える', description:'30秒〜数分で次の活動へ'},
  {id:'routine', label:'毎日の手順を育てる', description:'合図・声かけ・見通しをそろえる'},
  {id:'grow', label:'力と関係を育てる', description:'SST・SGE・PAでじっくり学ぶ'}
];
const catalog = {version:1, issues, stages, activities};
if (activities.length !== 50 || new Set(activities.map(x => x.id)).size !== 50) throw new Error('Expected 50 unique activities');
for (const item of activities) {
  for (const key of ['title','opening','closing','nextAction','adjustment','participation']) if (!item[key]) throw new Error(`${item.id}: missing ${key}`);
  for (const key of ['issues','grades','scenes','steps','projection']) if (!Array.isArray(item[key]) || !item[key].length) throw new Error(`${item.id}: missing ${key}`);
  if (!stages.some(x => x.id === item.stage)) throw new Error(`${item.id}: invalid stage`);
}
fs.writeFileSync(new URL('catalog.js',import.meta.url), '// Generated by build-catalog.mjs. Edit the JSON sources.\nwindow.MANABITANE_CATALOG = '+JSON.stringify(catalog,null,2)+';\n');
console.log(`Built ${activities.length} practice cards.`);
